import { createAction, ActionCreatorWithPreparedPayload, PayloadAction } from '@reduxjs/toolkit';
/**
 * Options for controlling the behavior of executeUseCase.
 * @typeParam T - The return type of the use case, used for the successCallback.
 */
export interface UseCaseOptions<T> {
	/**
	 * If true, skips dispatching the fulfilled action.
	 */
	skipSuccessDispatch?: boolean;

	/**
	 * If true, skips dispatching the rejected action.
	 */
	skipErrorDispatch?: boolean;

	/**
	 * Optional callback invoked on successful execution of the use case.
	 * Receives the result of the use case.
	 */
	successCallback?: (response: T) => void;

	/**
	 * Optional callback invoked on error during execution.
	 * Receives the error object.
	 */
	rejectCallback?: (error: any) => void;
}

/**
 * Interface defining the structure of asynchronous actions generated by createAsyncActions.
 * @typeParam S - The type of the payload for the `fulfilled` action (e.g., `ApiResponse<OrderDto>`).
 */
export interface AsyncActions<S = any> {
	/**
	 * The `pending` action, indicating the start of an asynchronous operation.
	 * Accepts an optional argument of any type as its payload.
	 * Includes a `meta.arg` field with the same value as the payload (or `undefined` if not provided).
	 */
	pending: ActionCreatorWithPreparedPayload<[any?], any | undefined, string, never, { arg: any | undefined }>;

	/**
	 * The `fulfilled` action, indicating the success of an asynchronous operation.
	 * Its payload is of the type specified by `S`.
	 * Includes a `meta.arg` field set to `undefined`, as it does not receive the original `pending` argument.
	 */
	fulfilled: ActionCreatorWithPreparedPayload<[S], S, string, never, { arg: any | undefined }>;

	/**
	 * The `rejected` action, indicating an error in the asynchronous operation.
	 * Its payload is a `string` representing the error message.
	 * Includes a `meta.arg` field set to `undefined`, as it does not receive the original `pending` argument.
	 */
	rejected: ActionCreatorWithPreparedPayload<[string], string, string, never, { arg: any | undefined }>;
}

/**
 * Represents a generic use case interface.
 *
 * @typeParam T - The type of the result returned by the use case.
 * @typeParam P - The type of the parameters required to execute the use case.
 */
export interface UseCaseInterface<T, P> {
	execute(params: P): Promise<T>;
}

/**
 * Interface defining an asynchronous action with an optional meta field.
 * Extends AsyncAction to include a meta field for Redux Toolkit actions.
 * @typeParam P - The type of the payload (e.g., `string` or `undefined`).
 * @typeParam M - The type of the meta field (defaults to `{ arg: P }`).
 */
export interface AsyncAction<P, M = { arg: P }> extends PayloadAction<P> {
	meta?: M;
}


/**
 * An abstraction layer for IoC containers to ensure the library remains decoupled 
 * from specific dependency injection frameworks.
 */
export interface IoCContainer {
	resolve: <T>(target: new (...args: any[]) => T) => T;
}
